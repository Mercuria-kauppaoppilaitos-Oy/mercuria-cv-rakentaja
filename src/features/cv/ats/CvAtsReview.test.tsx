import { render, screen, within, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { expect, it } from 'vitest';
import { App } from '../../../App';
import { selectStep } from '../../../test/navigation';
it('vaatii vahvistuksen, lisää näkyvän taidon ja pitää ilmoituksen poissa luonnoksesta', async () => {
  const user = userEvent.setup(); render(<App />);
  await selectStep(user, 'Viimeistele');
  await user.type(screen.getByLabelText('Työpaikkailmoitus'), 'Edellytämme CRM osaamista. Tarjoamme ILMOITUSSALAISUUS.');
  await user.click(screen.getByRole('button', { name: 'Analysoi ilmoitus' }));
  await waitFor(() => expect(screen.getByRole('heading', { name: 'Ilmoitusvertailun tulokset' })).toHaveFocus());
  const missing = screen.getByRole('region', { name: 'Ei vielä löydy CV:stä' });
  await user.click(within(missing).getByRole('button', { name: 'Lisää ehdotus CV:hen: CRM' }));
  const add = screen.getByRole('button', { name: 'Lisää vahvistettu taito: CRM' });
  expect(add).toBeDisabled();
  await user.click(screen.getByLabelText('Vahvistan, että tämä vastaa omaa osaamistani tai kokemustani.'));
  await user.click(add);
  expect(within(screen.getByRole('region', { name: 'Löytyy CV:stä' })).getByRole('heading', { name: 'CRM' })).toBeVisible();
  expect(within(screen.getByRole('article')).getByText('CRM')).toBeVisible();
  await waitFor(() => expect(sessionStorage.getItem('mercuria-cv-draft-v1')).toContain('CRM'));
  expect(sessionStorage.getItem('mercuria-cv-draft-v1')).not.toContain('ILMOITUSSALAISUUS');
  await selectStep(user, 'Osaaminen'); await selectStep(user, 'Viimeistele');
  expect(screen.getByLabelText('Työpaikkailmoitus')).toHaveValue('');
});
it('ilmoittaa syötevirheen ja ohjaa epäselvän kokemuksen oikeaan vaiheeseen', async () => {
  const user = userEvent.setup(); render(<App />); await selectStep(user, 'Viimeistele');
  await user.click(screen.getByRole('button', { name: 'Analysoi ilmoitus' }));
  expect(screen.getByRole('alert')).toHaveTextContent('vähintään');
  await user.type(screen.getByLabelText('Työpaikkailmoitus'), 'Vaaditaan kolmen vuoden kokemus myymälässä.');
  await user.click(screen.getByRole('button', { name: 'Analysoi ilmoitus' }));
  await user.click(screen.getByRole('button', { name: 'Siirry muokkaamaan' }));
  expect(screen.getByRole('heading', { name: 'Työkokemus', level: 3 })).toHaveFocus();
  expect(screen.getByRole('status')).toHaveTextContent('kolmen vuoden');
});
